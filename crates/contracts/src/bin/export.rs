use dm_contracts::{
    AddDownloadRequest, BrowserFileEvidence, BrowserOperation, BrowserRequest, BrowserResponse,
    BrowserState, DownloadDetails, JobView,
};
use dm_domain::{
    AppError, DiagnosticEvent, EngineConnection, EngineHealth, ErrorCode, JobStatus, Settings,
    TransferDetails,
};
use ts_rs::TS;

fn main() {
    let declarations = [
        ErrorCode::decl(),
        AppError::decl(),
        JobStatus::decl(),
        Settings::decl(),
        AddDownloadRequest::decl(),
        JobView::decl(),
        EngineConnection::decl(),
        TransferDetails::decl(),
        EngineHealth::decl(),
        DiagnosticEvent::decl(),
        DownloadDetails::decl(),
        BrowserFileEvidence::decl(),
        BrowserOperation::decl(),
        BrowserRequest::decl(),
        BrowserState::decl(),
        BrowserResponse::decl(),
    ];
    let content = format!(
        "// Generated by cargo run -p dm-contracts --bin export. Do not edit.\n{}\n",
        declarations.map(|s| format!("export {s}")).join("\n\n")
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/contracts/src/index.ts");
    let content = content
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    if std::env::args().any(|a| a == "--check") {
        assert_eq!(
            std::fs::read_to_string(path).expect("Run pnpm contracts first"),
            content,
            "Contract drift: run pnpm contracts"
        );
    } else {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, content).unwrap();
    }
}
